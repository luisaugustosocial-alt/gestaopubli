-- GestãoPubli: schema inicial para Supabase/Postgres.
-- Revise e teste as políticas em um projeto de desenvolvimento antes de produção.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  full_name text not null default '',
  brand_name text not null default '',
  watermark_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  client_name text not null default '',
  description text not null default '',
  status text not null default 'briefing' check (status in ('briefing','in_progress','review','completed','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project_members (
  project_id uuid not null references public.projects(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'collaborator' check (role in ('owner','admin','collaborator','viewer')),
  created_at timestamptz not null default now(),
  primary key(project_id,user_id)
);

create table if not exists public.project_folders (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  name text not null,
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.project_files (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  folder_id uuid references public.project_folders(id) on delete set null,
  uploaded_by uuid not null references auth.users(id) on delete cascade,
  storage_path text not null,
  file_name text not null,
  mime_type text,
  size_bytes bigint,
  created_at timestamptz not null default now()
);

create table if not exists public.post_approvals (
  id uuid primary key default gen_random_uuid(),
  project_id uuid references public.projects(id) on delete cascade,
  designer_id uuid not null references auth.users(id) on delete cascade,
  client_name text not null default '',
  client_email text,
  title text not null,
  storage_path text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected','changes_requested')),
  share_token_hash text unique,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.approval_comments (
  id uuid primary key default gen_random_uuid(),
  approval_id uuid not null references public.post_approvals(id) on delete cascade,
  author_id uuid references auth.users(id) on delete set null,
  author_label text not null default '',
  body text not null,
  x_percent numeric(5,2),
  y_percent numeric(5,2),
  created_at timestamptz not null default now()
);

create table if not exists public.service_rates (
  id uuid primary key default gen_random_uuid(),
  designer_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.quotes (
  id uuid primary key default gen_random_uuid(),
  designer_id uuid not null references auth.users(id) on delete cascade,
  quote_number bigint generated by default as identity unique,
  client_name text not null,
  items jsonb not null default '[]'::jsonb,
  total numeric(12,2) not null default 0,
  status text not null default 'draft' check (status in ('draft','sent','approved','rejected','expired')),
  created_at timestamptz not null default now()
);

create table if not exists public.contracts (
  id uuid primary key default gen_random_uuid(),
  designer_id uuid not null references auth.users(id) on delete cascade,
  contract_number bigint generated by default as identity unique,
  client_name text not null,
  scope text not null,
  generated_text text,
  status text not null default 'draft' check (status in ('draft','review','sent','signed','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.social_accounts (
  id uuid primary key default gen_random_uuid(),
  designer_id uuid not null references auth.users(id) on delete cascade,
  client_name text not null default '',
  provider text not null default 'instagram',
  provider_account_id text not null,
  token_secret_ref text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.social_posts (
  id uuid primary key default gen_random_uuid(),
  designer_id uuid not null references auth.users(id) on delete cascade,
  social_account_id uuid not null references public.social_accounts(id) on delete cascade,
  caption text not null default '',
  media_path text not null,
  scheduled_at timestamptz,
  status text not null default 'draft' check (status in ('draft','scheduled','published','failed')),
  provider_post_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.collaboration_invites (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references public.projects(id) on delete cascade,
  invited_by uuid not null references auth.users(id) on delete cascade,
  invited_email text not null,
  role text not null default 'collaborator',
  token_hash text not null unique,
  expires_at timestamptz not null,
  accepted_at timestamptz,
  created_at timestamptz not null default now()
);

