-- Profiles: users can read public profile cards and update only their own profile.
create policy "profiles are readable by authenticated users" on public.profiles for select to authenticated using (true);
create policy "users insert own profile" on public.profiles for insert to authenticated with check (id = auth.uid());
create policy "users update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Projects are visible to owners and explicit project members.
create policy "project members can view projects" on public.projects for select to authenticated using (owner_id = auth.uid() or exists(select 1 from public.project_members pm where pm.project_id = id and pm.user_id = auth.uid()));
create policy "users create own projects" on public.projects for insert to authenticated with check (owner_id = auth.uid());
create policy "owners update projects" on public.projects for update to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy "owners delete projects" on public.projects for delete to authenticated using (owner_id = auth.uid());

create policy "members can view memberships" on public.project_members for select to authenticated using (user_id = auth.uid() or exists(select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid()));
create policy "owners add project members" on public.project_members for insert to authenticated with check (exists(select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid()));
create policy "owners remove project members" on public.project_members for delete to authenticated using (exists(select 1 from public.projects p where p.id = project_id and p.owner_id = auth.uid()));

create policy "project members view folders" on public.project_folders for select to authenticated using (exists(select 1 from public.projects p where p.id = project_id and (p.owner_id = auth.uid() or exists(select 1 from public.project_members pm where pm.project_id = p.id and pm.user_id = auth.uid()))));
create policy "project members create folders" on public.project_folders for insert to authenticated with check (created_by = auth.uid() and exists(select 1 from public.projects p where p.id = project_id and (p.owner_id = auth.uid() or exists(select 1 from public.project_members pm where pm.project_id = p.id and pm.user_id = auth.uid() and pm.role in ('owner','admin','collaborator')))));
create policy "project members view files" on public.project_files for select to authenticated using (exists(select 1 from public.projects p where p.id = project_id and (p.owner_id = auth.uid() or exists(select 1 from public.project_members pm where pm.project_id = p.id and pm.user_id = auth.uid()))));
create policy "project members upload files" on public.project_files for insert to authenticated with check (uploaded_by = auth.uid() and exists(select 1 from public.projects p where p.id = project_id and (p.owner_id = auth.uid() or exists(select 1 from public.project_members pm where pm.project_id = p.id and pm.user_id = auth.uid()))));

create policy "designers manage own approvals" on public.post_approvals for all to authenticated using (designer_id = auth.uid()) with check (designer_id = auth.uid());
create policy "designers read approval comments" on public.approval_comments for select to authenticated using (exists(select 1 from public.post_approvals a where a.id = approval_id and a.designer_id = auth.uid()));
create policy "designers add approval comments" on public.approval_comments for insert to authenticated with check (author_id = auth.uid() and exists(select 1 from public.post_approvals a where a.id = approval_id and a.designer_id = auth.uid()));
create policy "designers manage own service rates" on public.service_rates for all to authenticated using (designer_id = auth.uid()) with check (designer_id = auth.uid());
create policy "designers manage own quotes" on public.quotes for all to authenticated using (designer_id = auth.uid()) with check (designer_id = auth.uid());
create policy "designers manage own contracts" on public.contracts for all to authenticated using (designer_id = auth.uid()) with check (designer_id = auth.uid());
create policy "designers manage own social accounts" on public.social_accounts for all to authenticated using (designer_id = auth.uid()) with check (designer_id = auth.uid());
create policy "designers manage own social posts" on public.social_posts for all to authenticated using (designer_id = auth.uid()) with check (designer_id = auth.uid());
create policy "invite owners can manage invites" on public.collaboration_invites for all to authenticated using (invited_by = auth.uid()) with check (invited_by = auth.uid());

